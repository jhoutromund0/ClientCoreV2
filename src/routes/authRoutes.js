const router = require('express').Router();
const c = require('../controllers/authController');
const a = require('../middleware/auth');
const wrap = require('../middleware/asyncHandler');
router.get('/login', wrap(c.loginPage));
router.post('/login', wrap(c.login));
router.post('/sair', a.requireAuth, wrap(c.logout));
router.get('/conta', a.requireAuth, wrap(c.account));
router.post('/conta/senha', a.requireAuth, wrap(c.changePassword));
router.post('/conta/sessoes/encerrar', a.requireAuth, wrap(c.endAllSessions));
router.post('/conta/sessoes/:id/encerrar', a.requireAuth, wrap(c.endSession));
router.get('/acesso/definir-senha', wrap(c.setupPage));
router.post('/acesso/definir-senha', wrap(c.setupPassword));
router.get('/usuarios', a.requireRole('admin'), (req, res) => res.redirect('/configuracoes/usuarios'));
router.post('/usuarios', a.requireRole('admin'), wrap(c.createUser));
router.post('/usuarios/:id', a.requireRole('admin'), wrap(c.updateUser));
router.post('/usuarios/:id/excluir', a.requireRole('admin'), wrap(c.removeUser));
module.exports = router;
